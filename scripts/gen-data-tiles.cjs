/**
 * Generate src/data-tiles.ts (all 170 visuals, randomTiles source) from _projects2.json
 * Output: src/data-tiles.ts + scripts/tiles-download.txt (URL list for 512px webp)
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'unveil-site', '_src', '_projects2.json');
const OUT_TS = path.join(__dirname, '..', 'src', 'data-tiles.ts');
const OUT_DL = path.join(__dirname, '..', 'scripts', 'tiles-download.txt');

const projects = JSON.parse(
  fs.readFileSync(SRC, { encoding: 'utf8' })
);

const tiles = [];
let idx = 0;
for (const p of projects) {
  for (const v of p.visuals || []) {
    if (!v.src) continue;
    // derive 512px webp URL (fit=max keeps aspect, short edge 512)
    const url512 = v.src
      .replace(/h=\d+/, 'h=512')
      .replace(/w=\d+/, 'w=512')
      .replace(/q=\d+/, 'q=70')
      .replace(/fm=\w+/, 'fm=webp');
    const file = `${String(idx).padStart(3, '0')}_${p.slug}`;
    tiles.push({
      id: idx,
      title: p.title,
      slug: p.slug,
      year: p.year,
      tags: p.tags || [],
      desc: p.seoDesc || '',
      w: v.w,
      h: v.h,
      // local 512px webp for fast loading (downloaded by scripts/download-tiles.ps1)
      src: `img/tiles/${file}.webp`,
      file,
    });
    idx++;
  }
}

// TS module
const lines = [
  '// AUTO-GENERATED by scripts/gen-data-tiles.cjs — do not edit',
  '// All 170 project visuals (randomTiles=true, shuffled at runtime like the source site)',
  '',
  'export interface TileData {',
  '  id: number;',
  '  title: string;',
  '  slug: string;',
  '  year: string;',
  '  tags: string[];',
  '  desc: string;',
  '  w: number;',
  '  h: number;',
  '  src: string;',
  '}',
  '',
  `export const TILE_COUNT = ${tiles.length};`,
  '',
  'export const TILES: TileData[] = [',
  ...tiles.map(
    (t) =>
      `  { id: ${t.id}, title: ${JSON.stringify(t.title)}, slug: ${JSON.stringify(t.slug)}, year: ${JSON.stringify(t.year)}, tags: ${JSON.stringify(t.tags)}, desc: ${JSON.stringify(t.desc)}, w: ${t.w}, h: ${t.h}, src: ${JSON.stringify(t.src)} },`
  ),
  '];',
  '',
];

fs.writeFileSync(OUT_TS, lines.join('\n'));
fs.writeFileSync(OUT_DL, tiles.map((t) => `${t.src}\t${t.file}`).join('\n'));
console.log(`tiles: ${tiles.length} -> ${OUT_TS}`);
console.log(`download list -> ${OUT_DL}`);
